package io.jafar.shell;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import picocli.CommandLine;

/** {@code jfr-shell compare <baseline> <candidate>}, the headless {@code jfr_compare}. */
class CompareCommandTest {

  /** Checked in: 14,202 execution samples. */
  private static final Path TCK =
      Path.of("..", "jfr-shell-tck", "src", "main", "resources", "tck-test.jfr")
          .toAbsolutePath()
          .normalize();

  /** Generated by the build from two different synthetic programs: a pair whose frames moved. */
  private static final Path TEST_AP = resource("test-ap.jfr");

  private static final Path TEST_JFR = resource("test-jfr.jfr");

  private final ByteArrayOutputStream out = new ByteArrayOutputStream();
  private final ByteArrayOutputStream err = new ByteArrayOutputStream();
  private PrintStream originalOut;
  private PrintStream originalErr;

  @BeforeEach
  void captureStreams() {
    originalOut = System.out;
    originalErr = System.err;
    System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
    System.setErr(new PrintStream(err, true, StandardCharsets.UTF_8));
  }

  @AfterEach
  void restoreStreams() {
    System.setOut(originalOut);
    System.setErr(originalErr);
  }

  @Test
  void printsATableForIdenticalRecordings() {
    assertEquals(0, run("compare", TCK.toString(), TCK.toString()), this::streams);

    String text = out.toString(StandardCharsets.UTF_8);
    assertTrue(text.contains("Baseline  " + TCK + ": datadog.ExecutionSample"), text);
    assertTrue(text.contains("Event rates (per second)"), text);
    assertTrue(text.contains("Self time (leaf frame share of samples)"), text);
    assertTrue(text.contains("Inclusive time"), text);
    assertTrue(text.contains("no frame moved by the noise floor or more"), text);
    assertTrue(text.contains("[INFO] No regression above the noise floor"), text);
    assertFalse(text.trim().startsWith("{"), "a table, not JSON: " + text);
  }

  @Test
  void printsJfrCompareKeysPlusInclusiveFramesAsJson() {
    assertEquals(
        0,
        run(
            "compare",
            TEST_AP.toString(),
            TEST_JFR.toString(),
            "--json",
            "--limit",
            "3",
            "--event-type",
            "jdk.ExecutionSample"),
        this::streams);

    JsonObject json =
        JsonParser.parseString(out.toString(StandardCharsets.UTF_8)).getAsJsonObject();
    assertEquals(
        List.of(
            "baseline",
            "candidate",
            "comparability",
            "metrics",
            "frames",
            "inclusiveFrames",
            "minDeltaPct",
            "sufficientSamples",
            "minSamplesPerRecording",
            "findings",
            "findingCounts"),
        new ArrayList<>(json.keySet()));

    JsonObject baseline = json.getAsJsonObject("baseline");
    assertEquals(TEST_AP.toString(), baseline.get("recordingPath").getAsString());
    assertEquals("jdk.ExecutionSample", baseline.get("eventType").getAsString());
    assertEquals(8000, baseline.get("samples").getAsLong());
    assertEquals(2000, json.getAsJsonObject("candidate").get("samples").getAsLong());
    assertEquals(1.0, json.get("minDeltaPct").getAsDouble());
    assertTrue(json.get("sufficientSamples").getAsBoolean());

    JsonArray frames = json.getAsJsonArray("frames");
    assertEquals(3, frames.size(), "--limit applies: " + frames);
    assertTrue(frames.get(0).getAsJsonObject().has("baselineSelfPct"), frames.toString());

    JsonArray inclusive = json.getAsJsonArray("inclusiveFrames");
    assertEquals(3, inclusive.size(), "--limit applies: " + inclusive);
    for (JsonElement row : inclusive) {
      JsonObject r = row.getAsJsonObject();
      assertTrue(r.has("baselineTotalPct") && r.has("candidateTotalPct"), r.toString());
      assertTrue(r.get("significant").getAsBoolean(), r.toString());
    }
    assertTrue(json.getAsJsonArray("findings").size() > 0);
  }

  @Test
  void minDeltaPctIsTheNoiseFloor() {
    assertEquals(
        0,
        run("compare", TEST_AP.toString(), TEST_JFR.toString(), "--json", "--min-delta-pct", "50"),
        this::streams);

    JsonObject json =
        JsonParser.parseString(out.toString(StandardCharsets.UTF_8)).getAsJsonObject();
    assertEquals(50.0, json.get("minDeltaPct").getAsDouble());
    assertEquals(0, json.getAsJsonArray("frames").size(), json.toString());
    assertEquals(0, json.getAsJsonArray("inclusiveFrames").size(), json.toString());
  }

  @Test
  void aMissingRecordingFailsWithItsName(@TempDir Path dir) {
    Path missing = dir.resolve("missing.jfr");
    assertEquals(1, run("compare", TCK.toString(), missing.toString()));
    assertTrue(
        err.toString(StandardCharsets.UTF_8).contains("JFR file not found: " + missing), streams());
    assertEquals("", out.toString(StandardCharsets.UTF_8));
  }

  @Test
  void aFileThatIsNotARecordingFailsWithItsName(@TempDir Path dir) throws Exception {
    Path notJfr = Files.writeString(dir.resolve("notes.jfr"), "not a recording\n");
    assertEquals(1, run("compare", notJfr.toString(), TCK.toString()));
    assertTrue(
        err.toString(StandardCharsets.UTF_8).contains("cannot read JFR recording " + notJfr),
        streams());
    assertEquals("", out.toString(StandardCharsets.UTF_8));
  }

  @Test
  void aMissingCandidateIsAUsageErrorWithUsageText() {
    // main() parses once before execute(); a usage error there must not escape as a stack trace.
    CommandLine.ParameterException e =
        org.junit.jupiter.api.Assertions.assertThrows(
            CommandLine.ParameterException.class,
            () -> new CommandLine(new Main()).parseArgs("compare", TCK.toString()));
    assertEquals(Main.USAGE_ERROR, Main.usageError(e));
    String text = err.toString(StandardCharsets.UTF_8);
    assertTrue(text.contains("Error: Missing required parameter"), streams());
    assertTrue(text.contains("Usage: jfr-shell compare"), streams());
  }

  @Test
  void aMalformedOptionIsAUsageError() {
    assertEquals(
        Main.USAGE_ERROR, run("compare", TCK.toString(), TCK.toString(), "--limit", "abc"));
    assertTrue(err.toString(StandardCharsets.UTF_8).contains("--limit"), streams());
  }

  @Test
  void twoRecordingsOfDifferentSamplerKindsAreComparedWithANote(@TempDir Path dir)
      throws Exception {
    // Execution samples (CPU) against native method samples (wall): jfr_compare compares them with
    // a note, and so must the CLI. perf_ab_run.sh treats any exit but 0 as a failed run.
    Path nativeSamples = nativeMethodSamples(dir.resolve("native.jfr"), 100);
    assertEquals(
        0, run("compare", TEST_AP.toString(), nativeSamples.toString(), "--json"), streams());
    JsonObject json =
        JsonParser.parseString(out.toString(StandardCharsets.UTF_8)).getAsJsonObject();
    assertEquals(
        "jdk.NativeMethodSample", json.getAsJsonObject("candidate").get("eventType").getAsString());
    assertTrue(
        json.get("comparability").toString().contains("Different execution sample event types"),
        json.get("comparability").toString());
  }

  @Test
  void aNonPositiveLimitIsAUsageError() {
    assertEquals(Main.USAGE_ERROR, run("compare", TCK.toString(), TCK.toString(), "--limit", "0"));
    String text = err.toString(StandardCharsets.UTF_8);
    assertTrue(text.contains("--limit must be positive"), streams());
    assertTrue(text.contains("Usage: jfr-shell compare"), streams());
    err.reset();
    assertEquals(
        Main.USAGE_ERROR, run("compare", TCK.toString(), TCK.toString(), "--min-delta-pct", "-1"));
    assertTrue(
        err.toString(StandardCharsets.UTF_8).contains("Usage: jfr-shell compare"), streams());
  }

  @Test
  void aRootPathIsNotFoundRatherThanACrash() {
    // A root has no file name; naming it must not throw.
    assertEquals(1, run("compare", "/", TCK.toString()));
    assertTrue(err.toString(StandardCharsets.UTF_8).contains("file not found: /"), streams());
  }

  @Test
  void listSampleTypesNamesAJfrSideByItsEventType() {
    assertEquals(
        0, run("compare", TCK.toString(), TCK.toString(), "--list-sample-types"), streams());
    String text = out.toString(StandardCharsets.UTF_8);
    assertTrue(text.contains("  datadog.ExecutionSample "), text);
    assertFalse(text.contains("datadog.ExecutionSample/"), "not what --event-type takes: " + text);
  }

  /** A recording with {@code count} {@code jdk.NativeMethodSample} events, one second apart. */
  private static Path nativeMethodSamples(Path file, int count) throws Exception {
    ByteArrayOutputStream bytes = new ByteArrayOutputStream();
    try (org.openjdk.jmc.flightrecorder.writer.api.Recording recording =
        org.openjdk.jmc.flightrecorder.writer.api.Recordings.newRecording(bytes)) {
      org.openjdk.jmc.flightrecorder.writer.api.Types types = recording.getTypes();
      org.openjdk.jmc.flightrecorder.writer.api.Type stackTrace =
          types.getType(org.openjdk.jmc.flightrecorder.writer.api.Types.JDK.STACK_TRACE);
      org.openjdk.jmc.flightrecorder.writer.api.Type thread =
          types.getType(org.openjdk.jmc.flightrecorder.writer.api.Types.JDK.THREAD);
      org.openjdk.jmc.flightrecorder.writer.api.Type event =
          recording.registerEventType("jdk.NativeMethodSample", t -> {});
      long start = System.nanoTime();
      for (int i = 0; i < count; i++) {
        long at = start + i * 1_000_000_000L;
        recording.writeEvent(
            event.asValue(
                v -> {
                  v.putField("stackTrace", stackTrace.nullValue());
                  v.putField("eventThread", thread.nullValue());
                  v.putField("startTime", at);
                }));
      }
    }
    return Files.write(file, bytes.toByteArray());
  }

  @Test
  void anErrorWithoutAMessageIsNamedByItsClass() {
    assertEquals("java.lang.NullPointerException", Main.describe(new NullPointerException()));
    assertEquals("boom", Main.describe(new IllegalStateException("boom")));
  }

  private static int run(String... args) {
    return new CommandLine(new Main()).execute(args);
  }

  private String streams() {
    return "stdout:\n"
        + out.toString(StandardCharsets.UTF_8)
        + "\nstderr:\n"
        + err.toString(StandardCharsets.UTF_8);
  }

  private static Path resource(String name) {
    return Path.of("..", "parser-core", "src", "test", "resources", name)
        .toAbsolutePath()
        .normalize();
  }
}
