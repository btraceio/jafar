package io.jafar.parser;

import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.jafar.parser.api.ConstantPools;
import io.jafar.parser.api.HandlerFactory;
import io.jafar.parser.api.JfrField;
import io.jafar.parser.api.JfrType;
import io.jafar.parser.api.MetadataLookup;
import io.jafar.parser.api.TypedJafarParser;
import io.jafar.parser.internal_api.RecordingStream;
import io.jafar.parser.internal_api.metadata.MetadataClass;
import io.jafar.parser.types.JFRThread;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.openjdk.jmc.flightrecorder.writer.api.Recording;
import org.openjdk.jmc.flightrecorder.writer.api.Recordings;
import org.openjdk.jmc.flightrecorder.writer.api.Type;
import org.openjdk.jmc.flightrecorder.writer.api.Types;

/**
 * A factory that does not implement {@link HandlerFactory#create} - one generated by an older
 * jafar-processor - cannot supply constant pool entries: its {@code get} reuses one instance per
 * thread, and the pool caches what it is given, so every entry would read as the last one decoded.
 * The default {@code create} used to fall back to {@code get} silently; it now fails, saying to
 * rebuild the factory.
 */
public class LegacyHandlerFactoryTest {
  @JfrType("test.WithThread")
  public interface WithThread {
    @JfrField("eventThread")
    JFRThread eventThread();
  }

  /** Like an old generated factory: get() only. */
  static final class GetOnlyThreadFactory implements HandlerFactory<JFRThread> {
    @Override
    public void bind(MetadataLookup metadata) {}

    @Override
    public JFRThread get(RecordingStream stream, MetadataClass metadata, ConstantPools pools) {
      throw new AssertionError("get() must not be used for a constant pool entry");
    }

    @Override
    public String getJfrTypeName() {
      return "java.lang.Thread";
    }

    @Override
    public Class<JFRThread> getInterfaceClass() {
      return JFRThread.class;
    }
  }

  @TempDir Path dir;

  @Test
  void pooledEntryFromAFactoryWithoutCreateFails() throws Exception {
    Path jfr = dir.resolve("thread.jfr");
    try (Recording r = Recordings.newRecording(jfr)) {
      Types types = r.getTypes();
      Type thread = types.getType(Types.JDK.THREAD);
      Type event =
          r.registerEventType("test.WithThread", t -> t.addField("seq", Types.Builtin.INT));
      r.writeEvent(
          event.asValue(
              v -> {
                v.putField("stackTrace", types.getType(Types.JDK.STACK_TRACE).nullValue());
                v.putField("eventThread", thread.asValue(t -> t.putField("javaName", "main")));
                v.putField("startTime", System.nanoTime());
                v.putField("seq", 1);
              }));
    }
    Exception thrown =
        assertThrows(
            Exception.class,
            () -> {
              try (TypedJafarParser p = TypedJafarParser.open(jfr.toString())) {
                p.registerFactory(new GetOnlyThreadFactory());
                p.handle(WithThread.class, (e, ctl) -> e.eventThread());
                p.run();
              }
            });
    StringBuilder chain = new StringBuilder();
    for (Throwable c = thrown; c != null; c = c.getCause()) {
      chain.append("\n  ").append(c);
    }
    assertTrue(
        chain.toString().contains("does not implement HandlerFactory.create"), chain.toString());
    assertTrue(
        chain.toString().contains("Rebuild it with the current jafar-processor"), chain.toString());
  }
}
